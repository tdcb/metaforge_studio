"""Unit tests for Multi-Dialect DDL (Snowflake, SQL Server, Oracle) and dbt Compilers."""
import yaml
from backend.app.metamodel.seed import build_default_project
from backend.app.compilers.snowflake import compile_snowflake_ddl
from backend.app.compilers.sql_server import compile_sql_server_ddl
from backend.app.compilers.oracle import compile_oracle_ddl
from backend.app.compilers.dbt_generator import compile_dbt_artifacts


def test_snowflake_compiler_features():
    project = build_default_project()
    ddl = compile_snowflake_ddl(project)

    assert "CREATE OR REPLACE TABLE CORE.DIM_CUSTOMER" in ddl
    assert "CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_RAW_CLAIMS" in ddl
    assert "CLUSTER BY (CLM_INCURRED_DT, PLCY_ID)" in ddl
    assert "DATA_RETENTION_TIME_IN_DAYS = 14" in ddl
    assert "WITH TAG (GOVERNANCE.PII_CLASSIFICATION = 'RESTRICTED_PII')" in ddl
    assert "FOREIGN KEY (PLCY_ID)" in ddl
    assert "REFERENCES CORE.DIM_POLICY (PLCY_ID) RELY;" in ddl


def test_sql_server_compiler_features():
    project = build_default_project()
    ddl = compile_sql_server_ddl(project)

    assert "CREATE TABLE [dbo].[DIM_CUSTOMER]" in ddl
    assert "IDENTITY(1,1)" in ddl
    assert "GENERATED ALWAYS AS ROW START" in ddl
    assert "PERIOD FOR SYSTEM_TIME ([SysStartTime], [SysEndTime])" in ddl
    assert "SYSTEM_VERSIONING = ON (HISTORY_TABLE = [dbo].[DIM_CUSTOMER_HISTORY])" in ddl
    assert "CREATE CLUSTERED COLUMNSTORE INDEX [CCI_FCT_CLAIM] ON [claims].[FCT_CLAIM] ON [FG_CLAIMS_FACT]" in ddl
    assert "sp_addextendedproperty @name=N'MS_Description'" in ddl
    assert "GO" in ddl


def test_oracle_compiler_features():
    project = build_default_project()
    ddl = compile_oracle_ddl(project)

    assert "CREATE TABLE CORE_DATA.DIM_CUSTOMER" in ddl
    assert "VARCHAR2(150 CHAR)" in ddl
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "USING INDEX TABLESPACE USERS_IDX" in ddl
    assert "TABLESPACE CLAIMS_TBS" in ddl
    assert "COMPRESS FOR OLTP" in ddl
    assert "PARTITION BY RANGE (CLM_INCURRED_DT)" in ddl
    assert "COMMENT ON TABLE CORE_DATA.DIM_CUSTOMER IS" in ddl
    assert "COMMENT ON COLUMN CORE_DATA.DIM_CUSTOMER.CUST_FULL_NM IS" in ddl


def test_dbt_artifact_compiler():
    project = build_default_project()
    artifacts = compile_dbt_artifacts(project)

    assert "dbt_project.yml" in artifacts
    assert "models/sources.yml" in artifacts
    assert "models/schema.yml" in artifacts
    assert "models/core/dim_customer.sql" in artifacts
    assert "models/claims/fct_claim.sql" in artifacts

    parsed_schema = yaml.safe_load(artifacts["models/schema.yml"])
    assert parsed_schema["version"] == 2
    model_names = [m["name"] for m in parsed_schema["models"]]
    assert "dim_customer" in model_names
    assert "fct_claim" in model_names

    fct_sql = artifacts["models/claims/fct_claim.sql"]
    assert "materialized='incremental'" in fct_sql
    assert "ref('dim_policy')" in fct_sql
    assert "ref('dim_customer')" in fct_sql
