"""Oracle Database (PL/SQL) Enterprise DDL Compiler (Tables, Views, Materialized Views & ILM Retention)."""
from typing import List, Optional
from ..metamodel.schema import EntityModel, ProjectMetamodel, TargetDialect
from .view_builder import compile_view_ddl


def _escape_oracle(val: str) -> str:
    return val.replace("'", "''")


def compile_oracle_entity(entity: EntityModel, model: Optional[ProjectMetamodel] = None) -> str:
    if getattr(entity, "entity_type", "table") in ("view", "materialized_view") and model is not None:
        return compile_view_ddl(entity, model, TargetDialect.ORACLE)

    ora = entity.oracle_props
    ret = entity.retention_policy
    schema_name = (ora.schema_name or "CORE_DATA").upper()
    table_name = entity.physical_name.upper()
    tablespace = (ora.tablespace or "USERS").upper()
    idx_tablespace = (ora.index_tablespace or "USERS_IDX").upper()
    full_name = f"{schema_name}.{table_name}"

    lines: List[str] = []
    lines.append("-- =============================================================================")
    lines.append(
        f"-- Entity: {entity.logical_name} ({full_name}) | Tablespace: {tablespace} | Stereotype: {entity.modeling_stereotype}"
    )
    lines.append(
        f"-- Retention Policy: {ret.regulatory_framework} | Hot: {ret.active_retention_days}d | Archive: {ret.archive_retention_days}d"
    )
    lines.append("-- =============================================================================")

    has_identity = any(c.is_identity for c in entity.columns)
    if has_identity:
        lines.append(
            f"CREATE SEQUENCE {schema_name}.SEQ_{table_name} START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;"
        )
        lines.append("")

    lines.append(f"CREATE TABLE {full_name} (")

    col_defs: List[str] = []
    pk_cols: List[str] = []

    for col in entity.columns:
        col_name = col.physical_name.upper()
        dtype = col.data_type_oracle or "VARCHAR2(255 CHAR)"
        parts = [f"    {col_name:<28} {dtype}"]

        if col.is_identity and "NUMBER" in dtype.upper():
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        elif col.default_value is not None and str(col.default_value).strip() != "":
            parts.append(f"DEFAULT {col.default_value}")

        if not col.is_nullable or col.is_pk:
            parts.append("NOT NULL")
        if (col.is_unique or col.is_ak) and not col.is_pk:
            parts.append(f"CONSTRAINT UQ_{table_name}_{col_name} UNIQUE USING INDEX TABLESPACE {idx_tablespace}")
        if col.check_constraint:
            parts.append(f"CONSTRAINT CK_{table_name}_{col_name} CHECK ({col.check_constraint})")

        col_defs.append(" ".join(parts))
        if col.is_pk:
            pk_cols.append(col_name)

    if pk_cols:
        pk_expr = ", ".join(pk_cols)
        col_defs.append(
            f"    CONSTRAINT PK_{table_name} PRIMARY KEY ({pk_expr})\n"
            f"        USING INDEX TABLESPACE {idx_tablespace}"
        )

    lines.append(",\n".join(col_defs))
    lines.append(")")

    compress_clause = "COMPRESS FOR OLTP" if ora.compress_for_oltp else "NOCOMPRESS"
    lines.append(f"TABLESPACE {tablespace}")
    lines.append(f"PCTFREE {ora.pctfree}")
    lines.append(compress_clause)

    if ora.partition_by_range_col:
        interval_expr = ora.partition_interval or "NUMTOYMINTERVAL(1, 'MONTH')"
        lines.append(
            f"PARTITION BY RANGE ({ora.partition_by_range_col.upper()}) "
            f"INTERVAL ({interval_expr}) (\n"
            f"    PARTITION P_INITIAL VALUES LESS THAN (TO_DATE('2020-01-01', 'YYYY-MM-DD')) TABLESPACE {tablespace}\n"
            f")"
        )
    elif ora.partition_by_list_col:
        lines.append(
            f"PARTITION BY LIST ({ora.partition_by_list_col.upper()}) (\n"
            f"    PARTITION P_DEFAULT VALUES (DEFAULT) TABLESPACE {tablespace}\n"
            f")"
        )

    lines[-1] = lines[-1] + ";"

    if entity.description:
        lines.append("")
        lines.append(
            f"COMMENT ON TABLE {full_name} IS '{_escape_oracle(entity.description)}';"
        )

    for col in entity.columns:
        col_name = col.physical_name.upper()
        comment_parts: List[str] = []
        if col.description:
            comment_parts.append(col.description)
        if col.pii_classification != "NONE":
            comment_parts.append(f"[PII: {col.pii_classification}]")
        if comment_parts:
            merged_comment = " ".join(comment_parts)
            lines.append(
                f"COMMENT ON COLUMN {full_name}.{col_name} IS '{_escape_oracle(merged_comment)}';"
            )

    return "\n".join(lines)


def compile_oracle_ddl(
    model: ProjectMetamodel,
    subject_area: Optional[str] = None,
) -> str:
    """Compile full Oracle PL/SQL DDL script for the ProjectMetamodel."""
    header = [
        "-- *****************************************************************************",
        "-- MetaForge Studio - Oracle Database (PL/SQL) Enterprise DDL",
        f"-- Project: {model.name} (v{model.version})",
        "-- Features: VARCHAR2 CHAR semantics, TABLESPACE, USING INDEX TABLESPACE, Partitioning, OLTP Compression, Views",
        "-- *****************************************************************************",
        "",
    ]

    entities = [
        e
        for e in model.entities.values()
        if not subject_area or subject_area == "All" or e.subject_area == subject_area
    ]
    entity_ids = {e.id for e in entities}

    blocks = [compile_oracle_entity(ent, model) for ent in entities]

    fk_statements: List[str] = []
    for rel in model.relationships.values():
        if rel.parent_entity_id not in entity_ids or rel.child_entity_id not in entity_ids:
            continue
        parent_ent = model.entities.get(rel.parent_entity_id)
        child_ent = model.entities.get(rel.child_entity_id)
        if not parent_ent or not child_ent:
            continue

        if (
            rel.rel_type.value == "upstream_lineage"
            or getattr(parent_ent, "entity_type", "table") != "table"
            or getattr(child_ent, "entity_type", "table") != "table"
        ):
            fk_statements.append(
                f"-- [UPSTREAM/DOWNSTREAM LINEAGE] {parent_ent.physical_name.upper()} ---> {child_ent.physical_name.upper()} ({rel.name})"
            )
            continue

        parent_col = next((c for c in parent_ent.columns if c.id == rel.parent_column_id), None)
        child_col = next((c for c in child_ent.columns if c.id == rel.child_column_id), None)
        if not parent_col or not child_col:
            continue

        c_schema = (child_ent.oracle_props.schema_name or "CORE_DATA").upper()
        p_schema = (parent_ent.oracle_props.schema_name or "CORE_DATA").upper()
        c_idx_tbs = (child_ent.oracle_props.index_tablespace or "USERS_IDX").upper()
        fk_name = rel.name.upper()

        fk_statements.append(
            f"ALTER TABLE {c_schema}.{child_ent.physical_name.upper()}\n"
            f"    ADD CONSTRAINT {fk_name} FOREIGN KEY ({child_col.physical_name.upper()})\n"
            f"    REFERENCES {p_schema}.{parent_ent.physical_name.upper()} ({parent_col.physical_name.upper()});\n"
            f"CREATE INDEX {c_schema}.IX_{fk_name[:24]} ON {c_schema}.{child_ent.physical_name.upper()} "
            f"({child_col.physical_name.upper()}) TABLESPACE {c_idx_tbs};"
        )

    output = "\n\n".join(header + blocks)
    if fk_statements:
        output += "\n\n-- =============================================================================\n"
        output += "-- Foreign Key Constraints & Supporting B-Tree Indexes\n"
        output += "-- =============================================================================\n"
        output += "\n\n".join(fk_statements) + "\n"
    return output
