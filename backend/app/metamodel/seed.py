def ensure_seed_workspace(canonical_model_path: Path) -> ProjectMetamodel:
    """Ensure canonical_model.json exists on disk; if not, write the default seed model. Always sanitizes business text."""
    from .glossary import sanitize_model_business_text

    canonical_model_path.parent.mkdir(parents=True, exist_ok=True)
    if canonical_model_path.exists():
        try:
            raw = canonical_model_path.read_text(encoding="utf-8")
            project = ProjectMetamodel.model_validate_json(raw)
            sanitize_model_business_text(project)
            save_workspace_model(canonical_model_path, project)
            return project
        except Exception:
            pass
    project = build_default_project()
    sanitize_model_business_text(project)
    save_workspace_model(canonical_model_path, project)
    return project


def save_workspace_model(canonical_model_path: Path, project: ProjectMetamodel) -> None:
    """Persist ProjectMetamodel to workspace_model/canonical_model.json in formatted JSON."""
    canonical_model_path.parent.mkdir(parents=True, exist_ok=True)
    canonical_model_path.write_text(
        json.dumps(project.model_dump(mode="json"), indent=2),
        encoding="utf-8",
    )
